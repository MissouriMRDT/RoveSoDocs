// tools/build-minisearch-index.mjs
import fs from "node:fs/promises";
import path from "node:path";
import fg from "fast-glob";
import MiniSearch from "minisearch";
import * as cheerio from "cheerio";

const DIST_DIR = path.resolve("dist");
const ASSETS_DIR = path.join(DIST_DIR, "assets");
const CHUNKS_DIR = path.join(ASSETS_DIR, "chunks");

const STRIP_SELECTORS = [
  // VitePress chrome
  ".VPNav",
  ".VPSidebar",
  ".VPLocalNav",

  // Doxygen chrome (common)
  "#top",
  "#titlearea",
  "#side-nav",
  "#nav-tree",
  ".navpath",
  "#MSearchSelectWindow",
  "#MSearchResultsWindow",
];

function fileToUrl(relPath) {
  // Convert dist-relative file path -> clean URL
  // e.g. "autonomy/index.html" => "/autonomy/"
  let url = "/" + relPath.replaceAll(path.sep, "/");
  if (url.endsWith("/index.html"))
    url = url.slice(0, -"/index.html".length) + "/";
  return url;
}

function normalizeText(s) {
  return s
    .replace(/\s+/g, " ")
    .replace(/\u00a0/g, " ")
    .trim();
}

function sectionFromUrl(url) {
  if (url.startsWith("/autonomy/")) return "Autonomy (Doxygen)";
  if (url.startsWith("/RoveSoSimulator/_d/"))
    return "RoveSoSimulator (Doxygen)";
  if (url.startsWith("/RoveSoSimulator/_j/")) return "RoveSoSimulator (Jekyll)";
  if (url.startsWith("/embedded/")) return "Embedded Docs (Doxygen)";
  if (url.startsWith("/rovecomm/_cpp/")) return "RoveComm C++ (Doxygen)";
  return "Docs Hub";
}

async function dirExists(p) {
  try {
    const st = await fs.stat(p);
    return st.isDirectory();
  } catch {
    return false;
  }
}

async function findLocalSearchIndexChunkFiles() {
  // Should be located somewhere in dist. It will be named similar to: @localSearchIndexroot.MJNdQY7M.js
  // Search in preferred order:
  //   1) dist/assets/chunks (if it exists)
  //   2) dist/assets
  //   3) dist (last resort)
  const roots = [];
  if (await dirExists(CHUNKS_DIR)) roots.push(CHUNKS_DIR);
  if (await dirExists(ASSETS_DIR)) roots.push(ASSETS_DIR);
  roots.push(DIST_DIR);

  const patterns = [
    // exact-ish matches for what you showed
    "**/*@localSearchIndexroot*.js",
    "**/*@localSearchIndexroot*.mjs",
    "**/*_@localSearchIndexroot*.js",
    "**/*_@localSearchIndexroot*.mjs",

    // fallback if naming changes slightly
    "**/*@localSearchIndex*.js",
    "**/*@localSearchIndex*.mjs",
    "**/*_@localSearchIndex*.js",
    "**/*_@localSearchIndex*.mjs",
  ];

  for (const root of roots) {
    const matches = await fg(patterns, {
      cwd: root,
      onlyFiles: true,
      dot: true,
      absolute: true,
      caseSensitiveMatch: false,
      unique: true,
    });

    if (matches.length) {
      // Prefer the "...Indexroot..." file(s) if both sets matched
      const preferred = matches.filter((p) =>
        /localSearchIndexroot/i.test(path.basename(p)),
      );
      return preferred.length ? preferred : matches;
    }
  }

  // Debug dump: show some JS we *do* have in dist/assets (if any)
  const jsInAssets = (await dirExists(ASSETS_DIR))
    ? await fg(["**/*.js", "**/*.mjs"], {
        cwd: ASSETS_DIR,
        onlyFiles: true,
        dot: true,
        caseSensitiveMatch: false,
      })
    : [];

  const preview = jsInAssets
    .slice(0, 60)
    .map((f) => ` - ${f}`)
    .join("\n");

  throw new Error(
    `No local search chunk found.\n` +
      `Searched roots:\n${roots.map((r) => ` - ${r}`).join("\n")}\n` +
      `Tried patterns:\n${patterns.map((p) => ` - ${p}`).join("\n")}\n\n` +
      `First ${Math.min(60, jsInAssets.length)} JS files under dist/assets:\n` +
      (preview || " (none)\n") +
      `\nIf dist/assets is empty too, your build step isn't producing assets into this dist folder (or hasn't run yet).`,
  );
}

function toWebPath(absFile) {
  // abs filesystem path -> site web path (dist-relative, with /)
  const rel = path.relative(DIST_DIR, absFile);
  return "/" + rel.split(path.sep).join("/");
}

async function writeDebugRedirectPage(chunkFiles) {
  // pick first chunk as the redirect target (your finder already prefers Indexroot)
  const primary = chunkFiles[0];
  const primaryWeb = toWebPath(primary);

  const all = chunkFiles.map((f) => ({
    abs: f,
    web: toWebPath(f),
  }));

  // Base-path aware redirect:
  // - If deployed under /something/, and you visit /something/_debug/?search=...
  //   it will redirect to /something/assets/... not /assets/...
  const html = `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8" />
  <meta name="robots" content="noindex,nofollow" />
  <meta name="viewport" content="width=device-width, initial-scale=1" />
  <title>RoveSoDocs Debug Viewer</title>
</head>
<body style="font-family: system-ui, -apple-system, Segoe UI, Roboto, sans-serif; padding: 24px;">
  <h1>RoveSoDocs Debug Viewer</h1>
  <p>This page is generated by <code>tools/build-minisearch-index.mjs</code>.</p>

  <p><strong>Primary chunk:</strong> <a id="primaryLink" href="#">(loading...)</a></p>
  <details>
    <summary>All matched chunk files</summary>
    <ul id="allLinks"></ul>
  </details>

  <p style="margin-top: 16px; opacity: 0.8;">
    Tip: add <code>?search=anything</code> to auto-redirect.
  </p>

  <script>
    (function () {
      const params = new URLSearchParams(location.search);

      // detect base path by trimming everything after "/_debug"
      const p = location.pathname;
      const i = p.indexOf("/_debug");
      const base = i >= 0 ? p.slice(0, i) : "";

      const primary = base + ${JSON.stringify(primaryWeb)};
      document.getElementById("primaryLink").href = primary;
      document.getElementById("primaryLink").textContent = primary;

      const all = ${JSON.stringify(all.map((x) => x.web))};
      const ul = document.getElementById("allLinks");
      for (const w of all) {
        const a = document.createElement("a");
        a.href = base + w;
        a.textContent = base + w;
        const li = document.createElement("li");
        li.appendChild(a);
        ul.appendChild(li);
      }

      // redirect only when "?search" is present (value doesn't matter)
      if (params.has("search")) {
        location.replace(primary);
      }
    })();
  </script>
</body>
</html>
`;

  // Support both /_debug/ and /_debug
  await fs.mkdir(path.join(DIST_DIR, "_debug"), { recursive: true });
  await fs.writeFile(path.join(DIST_DIR, "_debug", "index.html"), html, "utf8");
  await fs.writeFile(path.join(DIST_DIR, "_debug.html"), html, "utf8");
}

async function main() {
  // Index built HTML pages. Ignore dist/assets/** because that’s JS/CSS, not docs content.
  const htmlFiles = await fg(["**/*.html"], {
    cwd: DIST_DIR,
    dot: true,
    onlyFiles: true,
    ignore: [
      "assets/**", // don't index JS/CSS bundles

      // don't index debug pages
      "_debug/**",
      "**/_debug/**",
      "_debug.html",

      // don't index search pages
      "**/search*.html",
      "**/search/**",

      // Doxygen helper pages (optional but helpful)
      "**/navtree*.html",
      "**/menudata*.html",
      "**/dynsections*.html",
    ],
  });

  const documents = [];
  for (const rel of htmlFiles) {
    const abs = path.join(DIST_DIR, rel);
    const html = await fs.readFile(abs, "utf8");
    const $ = cheerio.load(html);

    // Remove noise
    for (const sel of STRIP_SELECTORS) $(sel).remove();
    $("script, style, noscript").remove();

    const title =
      normalizeText($("title").first().text()) ||
      normalizeText($("h1").first().text()) ||
      rel;

    const bodyText = normalizeText($("body").text());
    if (!bodyText) continue;

    const url = fileToUrl(rel);
    const section = sectionFromUrl(url);

    // VitePress local search shape: title, titles, text
    documents.push({
      id: url, // IMPORTANT: VitePress local search uses doc IDs like "/path#hash"
      title,
      titles: [section],
      text: bodyText,
    });
  }

  const miniSearch = new MiniSearch({
    idField: "id",
    fields: ["title", "titles", "text"],
    storeFields: ["title", "titles"],
  });

  miniSearch.addAll(documents);

  // MiniSearch JSON string (what VitePress expects inside the chunk)
  const serialized = JSON.stringify(miniSearch);

  // Wrap like VitePress local-search chunk:
  // const e='...';export{e as default};
  // JSON.stringify(serialized) ensures safe JS string escaping.
  const jsModule = `const e=${JSON.stringify(serialized)};export{e as default};\n`;

  // Find & overwrite the generated local-search chunk(s)
  const chunkFiles = await findLocalSearchIndexChunkFiles();
  await Promise.all(chunkFiles.map((f) => fs.writeFile(f, jsModule, "utf8")));

  await writeDebugRedirectPage(chunkFiles);

  console.log(
    `Indexed ${documents.length} pages.\nOverwrote local-search chunk(s):\n` +
      chunkFiles.map((f) => " - " + path.relative(process.cwd(), f)).join("\n"),
  );
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
